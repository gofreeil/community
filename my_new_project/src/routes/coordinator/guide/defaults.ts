function isObj(v: unknown): v is Record<string, unknown> {
	return !!v && typeof v === 'object' && !Array.isArray(v);
}

/**
 * מיזוג תוכן שמור מעל ברירות המחדל, רקורסיבית:
 * - שדה שחסר ברשומה השמורה נופל לברירת המחדל - כך הוספת שדות עתידית
 *   בקוד לא נשברת מול תוכן ישן שכבר נשמר ב-DB.
 * - מפתחות שאינם חלק מהמבנה נזרקים (הידוק הצורה בשמירה).
 * - מערכים ממוזגים איבר-איבר מול איברי ברירת המחדל המקבילים.
 */
export function mergeGuide<T>(def: T, stored: unknown): T {
	if (typeof def === 'string') return (typeof stored === 'string' ? stored : def) as T;
	if (Array.isArray(def)) {
		if (!Array.isArray(stored)) return def;
		const len = Math.max(def.length, stored.length);
		const out: unknown[] = [];
		for (let i = 0; i < len; i++) {
			if (i < def.length && i < stored.length) out.push(mergeGuide(def[i], stored[i]));
			else if (i < stored.length) out.push(stored[i]);
			else out.push(def[i]);
		}
		return out as T;
	}
	if (isObj(def)) {
		if (!isObj(stored)) return def;
		const out: Record<string, unknown> = {};
		for (const k of Object.keys(def)) out[k] = mergeGuide((def as Record<string, unknown>)[k], stored[k]);
		return out as T;
	}
	return (stored === undefined ? def : stored) as T;
}
