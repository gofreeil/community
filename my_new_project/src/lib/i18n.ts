/** שפות הממשק. בחירה שמורה שאינה ברשימה (למשל 'ru' מלפני הסרת הרוסית) נופלת לעברית. */
const SUPPORTED_LOCALES: readonly string[] = ['he', 'en'];

function savedLocale(): string {
    try {
        const saved = typeof window !== 'undefined' ? localStorage.getItem('lang') : null;
        if (saved && SUPPORTED_LOCALES.includes(saved)) return saved;
    } catch {}
    return 'he';
}

init({
    fallbackLocale: 'he',
    // תמיד עברית כברירת מחדל — שפת המכשיר לא קובעת; רק בחירה ידנית שנשמרה
    initialLocale: savedLocale(),
});
