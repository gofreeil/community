// ============================================================
// statsMonthMerge.ts — מיזוג נתוני יוני לתוך יולי בכל גרפי הסטטיסטיקה.
// יוני (2026) הוא חודש טרום-השקה: היו בו הרשמות/פרסומים מוקדמים אך זו לא
// ההתחלה האמיתית של האתר — ההתחלה האמיתית היא יולי. לכן נתוני יוני מצורפים
// ליולי (כאילו נוצרו ביולי) ויוני עצמו מתאפס, בכל הגרפים, כדי שהתצוגה תהיה
// עקבית: הגרף המסכם והגרפים המפורטים מציגים את אותו הדבר.
// ============================================================

export const MERGE_FROM_MONTH = 5; // יוני (0=ינואר)
export const MERGE_INTO_MONTH = 6; // יולי — סופג את נתוני יוני

/**
 * ממזג את נתוני יוני לתוך יולי בסדרה של 12 חודשים.
 * מחזיר מערך חדש (לא משנה את המקור): יוני→0, יולי→יולי+יוני.
 */
export function mergeJuneIntoJuly(series: number[]): number[] {
	return series.map((v, i) => {
		if (i === MERGE_FROM_MONTH) return 0;
		if (i === MERGE_INTO_MONTH) return v + (series[MERGE_FROM_MONTH] ?? 0);
		return v;
	});
}
