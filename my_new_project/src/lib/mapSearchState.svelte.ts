// ============================================================
// mapSearchState.svelte.ts - גשר בין כפתור "חיפוש" בהדר לבין מצב
// החיפוש של המפה בדף הבית.
//
// ההדר חי ב-+layout והמפה (JerusalemMap) בדף הבית בלבד, אז הם לא
// יכולים להעביר props. ההדר מבקש (request++), המפה מגיבה ומדווחת
// חזרה אם היא מורכבת ואם מצב החיפוש פתוח - כדי שהכפתור יידע
// לנווט ל-/search כשאין מפה, ולהיראות "דלוק" כשהחיפוש פתוח.
// ============================================================

class MapSearchState {
    /** האם יש מפה מורכבת שמאזינה לבקשות (דף הבית). */
    mounted = $state(false);

    /** האם המפה מציגה כרגע את מצב החיפוש (מסונכרן מהמפה). */
    open = $state(false);

    /** מונה בקשות מההדר; המפה מגיבה לכל שינוי. */
    request = $state(0);

    /** בקשת פתיחה/סגירה של מצב החיפוש במפה. */
    toggle() {
        this.request++;
    }
}

export const mapSearchState = new MapSearchState();
